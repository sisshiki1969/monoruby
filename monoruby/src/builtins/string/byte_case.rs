//! Case maps of the single-byte encodings that have one of their own.
//!
//! In CRuby the case mapping of a string is its encoding's business
//! (`OnigEncodingType::case_map`). The Unicode encodings share
//! `onigenc_unicode_case_map`; US-ASCII, ASCII-8BIT, the IBM / Mac code
//! pages and every multibyte legacy encoding map the ASCII letters and
//! nothing else; and the ISO-8859 family and its Windows cousins each
//! carry a table of their own letters, with three things on top:
//!
//! - `ß` (0xDF where there is one) is `SS` upcased and swapcased, `Ss`
//!   capitalized and `ss` folded;
//! - a few bytes fold to something else than their lowercase (the final
//!   sigma, the micro sign of Windows-1253);
//! - `:turkic` moves `I` / `i` to the encoding's dotless `ı` / dotted
//!   `İ` where it has them — and, in Windows-1257, to the bytes ISO-8859-3
//!   keeps them at, which is what CRuby does.
//!
//! The tables below are CRuby's, read off the pinned release one byte at
//! a time (`"\xNN".force_encoding(enc).upcase` and friends) rather than
//! copied from `enc/*.c`, so that what is recorded is what the methods
//! answer. `byte_case_tables_match` in the parent module's tests samples
//! them against the oracle.

pub(super) struct ByteCaseMap {
    /// The uppercase of each byte `0x80..=0xFF` (itself when it has none).
    pub up: &'static [u8; 128],
    /// The lowercase of each byte `0x80..=0xFF` (itself when it has none).
    pub down: &'static [u8; 128],
    /// `0xDF` is `ß`.
    pub sharp_s: bool,
    /// The bytes whose fold is not their lowercase.
    pub fold: &'static [(u8, u8)],
    /// Under `:turkic`: what `I` downcases to and what `i` upcases to.
    pub turkic: Option<(u8, u8)>,
}

