#[test]
fn each_slice_and_each_cons_ask_the_receiver_for_its_size() {
    // #2227. CRuby's `limit_by_enum_size` / `enum_size_over_p`: a slice
    // is no longer than `size` says the whole is, and no window is
    // yielded when `size` is below the window. Only a Fixnum counts,
    // read as unsigned.
    run_test_once(
        r##"
        class E2227
          include Enumerable
          def initialize(s) = @s = s
          def each; yield 1; yield 2; yield 3; end
          def size = @s
        end
        class F2227
          include Enumerable
          def each; yield 1; yield 2; yield 3; end
        end
        class A2227 < Array; def size = 1; end
        $c2227 = 0
        class G2227
          include Enumerable
          def each; yield 1; yield 2; yield 3; end
          def size = ($c2227 += 1; 3)
        end
        r = [0, 1, 2, 5, -1, nil, 2.0, 2**70].map do |s|
          a = []; E2227.new(s).each_slice(2) { |x| a << x }
          b = []; E2227.new(s).each_cons(2) { |x| b << x }
          [a, b]
        end
        a = A2227.new([1, 2, 3])
        h = {a: 1, b: 2, c: 3}; def h.size = 1
        G2227.new.each_slice(2) { }; G2227.new.each_cons(2) { }
        r << [F2227.new.each_slice(2).to_a, F2227.new.each_cons(2).to_a,
              a.each_slice(2).to_a, a.each_cons(2).to_a,
              h.each_slice(2).to_a, h.each_cons(2).to_a, $c2227,
              [1, 2, 3].each_slice(2).to_a, [1, 2, 3].each_cons(2).to_a,
              (1..5).each_slice(2).to_a, (1..5).each_cons(4).to_a]
        "##,
    );
}

#[test]
fn binread_with_a_length_past_the_end() {
    // `File.binread(path, length)` reads up to `length` bytes; it
    // raised for a file shorter than that.
    run_test_once(
        r##"
        path = "/tmp/monoruby_binread_#{Process.pid}_#{rand(1 << 30)}"
        File.binwrite(path, "abcdef")
        r = [
          File.binread(path, 4), File.binread(path, 6), File.binread(path, 10),
          File.binread(path, 10, 2), File.binread(path, 10, 6), File.binread(path, 0, 6),
          File.binread(path, 0), File.binread(path, 3, nil), File.binread(path, nil, 4),
          File.binread(path, 10).encoding.to_s,
          (File.binread(path, -1) rescue [$!.class, $!.message]),
        ]
        File.unlink(path)
        r
        "##,
    );
}
