//! Where CRuby reads an index, a count or a width with `NUM2LONG`, the
//! conversion has rules of its own: `nil` is "no implicit conversion
//! from nil to integer" (not the `to_int` message), a Float truncates
//! without a call and one outside a `long` is a RangeError naming it.
//! monoruby used the `to_int` conversion at most of those sites (#2236).
//!
//! Also here: `format` with nil (#2237), `rand` with a Range that lacks
//! an end (#2237), and the arguments where CRuby takes nil as "not
//! given" or refuses it that turned up next to them.
//!
//! Each test evaluates a list of expressions and compares the answers,
//! or the exceptions' classes and messages, with CRuby's.

use monoruby::tests::*;

