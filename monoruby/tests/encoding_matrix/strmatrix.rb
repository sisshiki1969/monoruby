# bin/encoding-matrix isolates a crash: `LIST=units` / `LIST=cases` name
# the inputs / cases, `ONLY_INPUT=<input>` runs one input, and `SKIP` is
# `"<input>\t<case>|…"` for the rows that crashed the process.
case ENV["LIST"]
when "units" then puts INPUTS.keys; exit
when "cases" then puts CASES.keys; exit
end
only = ENV["ONLY_INPUT"]; skip = (ENV["SKIP"] || "").split("|")
INPUTS.each do |iname, s|
  next if only && iname != only
  CASES.each do |cname, blk|
    next if skip.include?("#{iname}\t#{cname}")
    $stdout.flush
    r = begin
      show(blk.call(s.dup))
    rescue Exception => e
      "#{e.class}: #{e.message.lines.first&.chomp}"
    end
    puts "#{iname}\t#{cname}\t#{r}"
  end
end
