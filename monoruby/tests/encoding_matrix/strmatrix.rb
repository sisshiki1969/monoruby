def show(v)
  case v
  when String then "#{v.inspect}/#{v.encoding}/#{v.valid_encoding?}/#{v.ascii_only?}/#{v.frozen?}"
  when Array then "[" + v.map { |x| show(x) }.join(", ") + "]"
  when Symbol then "#{v.inspect}/#{v.encoding}"
  when Enumerator then "enum:" + show(v.first(3))
  when Regexp then "#{v.inspect}/#{v.encoding}/#{v.fixed_encoding?}"
  when MatchData then "md:" + show(v.to_a)
  else v.inspect
  end
end
